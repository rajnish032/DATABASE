WHERE STUDENT_ID IN (
    SELECT STUDENT_ID
    FROM ENROLLMENT
);

SELECT STUDENT_NAME
FROM STUDENT
WHERE DEPT_ID IS NOT NULL;

SELECT COURSE_NAME
