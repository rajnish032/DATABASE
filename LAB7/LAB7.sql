    SELECT COURSE_ID
    FROM ENROLLMENT
);

--Analytical Subqueries

SELECT COURSE_NAME
FROM COURSE
WHERE CREDITS = (
    SELECT MAX(CREDITS)
    FROM COURSE
);

SELECT STUDENT_NAME
FROM STUDENT
WHERE STUDENT_ID IN (
    SELECT STUDENT_ID
    FROM ENROLLMENT
    GROUP BY STUDENT_ID
    HAVING COUNT(*) > 1
);

SELECT DEPT_ID
FROM STUDENT
GROUP BY DEPT_ID
HAVING COUNT(*) = (
    SELECT MAX(cnt)
    FROM (
        SELECT COUNT(*) cnt
        FROM STUDENT
        GROUP BY DEPT_ID
    )
);


